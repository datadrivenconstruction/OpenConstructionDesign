pub const COMMAND: &str = "help.licenses";

const LICENSES: &str = include_str!("../../data/licenses.txt");

/// Facts shown on the About page and copied for a bug report. No paths, no user names.
#[derive(Clone, Debug, Default)]
pub struct AboutInfo {
    pub version: String,
    pub commit: Option<String>,
    pub date: Option<String>,
    pub schema: i64,
    pub os: String,
    pub gpu: String,
    pub lang: String,
}

/// Build commit and date from the build environment; either may be absent.
pub fn build_env() -> (Option<String>, Option<String>) {
    (
        option_env!("DDC_BUILD_COMMIT").map(str::to_string),
        option_env!("DDC_BUILD_DATE").map(str::to_string),
    )
}

pub fn about_info(app: &EditorApp) -> AboutInfo {
    let f = report_win::facts(app);
    let (commit, date) = build_env();
    AboutInfo {
        version: f.version,
        commit,
        date,
        schema: ddc_model::SCHEMA_VERSION,
        os: f.os,
        gpu: f.gpu,
        lang: f.lang,
    }
}

/// Build label: `<commit> <date>`, or `dev` when the build env is empty.
pub fn build_label(commit: Option<&str>, date: Option<&str>) -> String {
    let commit = commit.map(str::trim).filter(|s| !s.is_empty());
    let date = date.map(str::trim).filter(|s| !s.is_empty());
    match (commit, date) {
        (None, _) => "dev".to_string(),
        (Some(c), None) => c.to_string(),
        (Some(c), Some(d)) => format!("{c} {d}"),
    }
}

/// Replace the home directory and the user name in a value so a copied report stays private.
fn scrub(value: &str, home: &[String]) -> String {
    let mut out = value.to_string();
    for h in home.iter().filter(|h| h.len() > 2) {
        out = out.replace(h.as_str(), "~");
    }
    out
}

fn home_markers() -> Vec<String> {
    ["USERPROFILE", "HOME", "USERNAME", "USER"]
        .iter()
        .filter_map(|k| std::env::var(k).ok())
        .collect()
}

/// (label key, value) rows in display order.
pub fn about_lines(i: &AboutInfo) -> Vec<(&'static str, String)> {
    let home = home_markers();
    let mut v = vec![
        ("about.version", i.version.clone()),
        ("about.build", build_label(i.commit.as_deref(), i.date.as_deref())),
        ("about.schema", i.schema.to_string()),
        ("about.system", i.os.clone()),
        ("about.gpu", i.gpu.clone()),
        ("about.language", i.lang.clone()),
    ];
    for (_, val) in v.iter_mut() {
        *val = scrub(val, &home);
    }
    v
}

/// Text for the clipboard; labels in English so a report reads the same in any UI language.
pub fn copy_text(i: &AboutInfo, c: &Catalog) -> String {
    let mut t = format!("{}\n", c.t_in(Lang::En, "about.product"));
    for (k, val) in about_lines(i) {
        t.push_str(&format!("{}: {}\n", c.t_in(Lang::En, k), val));
    }
    t
}

const FULL_TEXTS: &str = include_str!("../../../../THIRD_PARTY_LICENSES.txt");

/// Full license and notice texts of every shipped component (generated by tools/gen_third_party.py).
pub fn full_texts() -> &'static str {
    FULL_TEXTS
}

thread_local! {
    static FULL: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
}

/// Parsed licenses, sorted by name; blank and `#` lines are skipped.
pub fn parse_licenses(src: &str) -> Vec<(String, String)> {
    let mut v: Vec<(String, String)> = src
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter_map(|l| {
            let mut p = l.splitn(3, '|');
            let name = p.next()?.trim();
            let ver = p.next()?.trim();
            let lic = p.next()?.trim();
            Some((format!("{name} {ver}"), lic.to_string()))
        })
        .collect();
    v.sort_by_key(|(n, _)| n.to_lowercase());
    v
}

pub fn licenses() -> Vec<(String, String)> {
    parse_licenses(LICENSES)
}

/// False when the file is empty: the About row is hidden then.
pub fn has_licenses() -> bool {
    !licenses().is_empty()
}

/// Width of the license column: the longest expression in the data fits, a long name gives way.
pub const LICENSE_COL_W: f32 = 200.0;
const SEARCH_ICON_X: f32 = space::XS;
const SEARCH_TEXT_X: f32 = space::XS + icon_size::SM + space::SM;
const SEARCH_ID: &str = "licenses.search";

thread_local! {
    static OPEN: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
    static FOCUS: std::cell::Cell<bool> = const { std::cell::Cell::new(false) };
    static QUERY: std::cell::RefCell<String> = const { std::cell::RefCell::new(String::new()) };
    static LIST: std::cell::RefCell<Vec<(String, String)>> = const { std::cell::RefCell::new(Vec::new()) };
}

pub(crate) fn open_window() {
    OPEN.with(|o| o.set(true));
    FOCUS.with(|f| f.set(true));
    QUERY.with(|q| q.borrow_mut().clear());
}

/// Indices of the rows whose name or license contains every word of `query` (any case).
pub fn matching(list: &[(String, String)], query: &str) -> Vec<usize> {
    let words: Vec<String> = query.split_whitespace().map(str::to_lowercase).collect();
    list.iter()
        .enumerate()
        .filter(|(_, (n, l))| {
            let hay = format!("{n} {l}").to_lowercase();
            words.iter().all(|w| hay.contains(w.as_str()))
        })
        .map(|(i, _)| i)
        .collect()
}

/// Count line: all components, or `shown of total` while a search is active.
pub fn count_text(c: &Catalog, shown: usize, total: usize, searching: bool) -> String {
    if searching {
        c.tf(
            "about.licenses.count_of",
            &[("shown", &shown.to_string()), ("total", &total.to_string())],
        )
    } else {
        c.plural("about.licenses.count", total as u64)
    }
}

/// Name takes the free width, the license keeps its fixed column.
pub fn columns<'a>(name: &'a str, license: &'a str) -> [Column<'a>; 2] {
    [
        Column::text(name).sortable(false),
        Column::text(license).fixed(LICENSE_COL_W).sortable(false),
    ]
}

/// Window content above the footer: note, count, search and the two-column list.
fn body(
    ui: &mut egui::Ui,
    th: &Theme,
    c: &Catalog,
    list: &[(String, String)],
    query: &mut String,
    focus: bool,
) {
    ui.label(
        RichText::new(c.t("about.licenses.note"))
            .font(th.font(Role::Body))
            .color(th.c("text.secondary")),
    );
    let show_full = FULL.with(std::cell::Cell::get);
    let (list_t, full_t) = (c.t("about.licenses.list"), c.t("about.licenses.full"));
    if let Some(i) = ddc_ui::widgets::segmented(ui, th, &[list_t.as_str(), full_t.as_str()], show_full as usize) {
        FULL.with(|f| f.set(i == 1));
    }
    if show_full {
        let lines: Vec<&str> = full_texts().lines().collect();
        let h = th.d().row;
        egui::ScrollArea::vertical().auto_shrink([false, false]).max_height((ui.available_height() - h * 3.0).max(h * 4.0)).show_rows(ui, h, lines.len(), |ui, range| {
            for l in &lines[range] {
                ui.label(RichText::new(*l).font(th.font(Role::Caption)).color(th.c("text.secondary")));
            }
        });
        return;
    }
    let searching = !query.trim().is_empty();
    let rows = matching(list, query);
    ui.label(
        RichText::new(count_text(c, rows.len(), list.len(), searching))
            .font(th.font(Role::Caption))
            .color(th.c("text.secondary")),
    );
    ui.add_space(space::SM);
    let id = egui::Id::new(SEARCH_ID);
    if focus {
        ui.memory_mut(|m| m.request_focus(id));
    }
    let hint = c.t("about.licenses.search_hint");
    let tip = c.t("about.licenses.search_clear");
    TextField::new(query)
        .id(id)
        .hint(&hint)
        .labelled_by(id.with("lbl"), &hint)
        .search("find", SEARCH_ICON_X, SEARCH_TEXT_X, &tip)
        .show(ui, th);
    ui.add_space(space::SM);
    if rows.is_empty() {
        let none_hint = c.t("about.licenses.none_hint");
        kit::empty_note(ui, c.t("about.licenses.none"), Some(none_hint.as_str()));
        return;
    }
    // Table::max_height bounds the body only; the header row is extra
    let footer_h = th.d().row
        + space::XS
        + stroke::HAIRLINE
        + th.d().control
        + 2.0 * ui.spacing().item_spacing.y
        + space::XS;
    let (n, l) = (c.t("about.licenses.col_name"), c.t("about.licenses.col_license"));
    let cols = columns(&n, &l);
    let mut sort = None;
    Table::new("licenses.table", &cols, rows.len())
        .max_height((ui.available_height() - footer_h).max(th.d().row * 4.0))
        .show(
            ui,
            th,
            &mut sort,
            |_| RowState::Normal,
            |r, col| {
                let (name, lic) = &list[rows[r]];
                if col == 0 {
                    Cell::text(name.clone())
                } else {
                    Cell::muted(lic.clone())
                }
            },
        );
}

pub fn is_open() -> bool {
    OPEN.with(std::cell::Cell::get)
}

pub fn register(app: &mut EditorApp) {
    app.register_command(COMMAND, |_| open_window());
}

pub fn frame(app: &EditorApp, ctx: &egui::Context) {
    if !is_open() {
        return;
    }
    LIST.with(|l| {
        let mut l = l.borrow_mut();
        if l.is_empty() {
            *l = licenses();
        }
    });
    let th = &app.sh.theme;
    let c = &app.sh.cat;
    let mut open = true;
    let mut close = false;
    kit::Dialog::new("licenses", c.t("about.licenses.title"), DialogSize::Tool)
        .open(&mut open)
        .stable()
        .show(ctx, |ui| {
            let focus = FOCUS.with(|f| f.replace(false));
            LIST.with(|l| {
                QUERY.with(|q| body(ui, th, c, &l.borrow(), &mut q.borrow_mut(), focus));
            });
            kit::dialog_footer(ui, |ui| {
                if kit::cancel_button(ui, c.t("about.licenses.close")).clicked() {
                    close = true;
                }
            });
        });
    if !open || close {
        OPEN.with(|o| o.set(false));
    }
}

