    fn texts(s: &egui::Shape, out: &mut Vec<(String, bool)>) {
        match s {
            egui::Shape::Text(t) => out.push((t.galley.text().to_string(), t.galley.elided)),
            egui::Shape::Vec(v) => v.iter().for_each(|x| texts(x, out)),
            _ => {}
        }
    }

    /// Text and "was elided" of every galley the list body drew in the last of three frames.
    fn draw(lang: Lang, list: &[(String, String)], query: &str) -> Vec<(String, bool)> {
        let ctx = font_ctx();
        let mut th = Theme::new(ddc_ui::Mode::Dark, ddc_ui::Density::Compact);
        let c = Catalog::new(lang);
        let mut q = query.to_string();
        let mut seen = vec![];
        for _ in 0..3 {
            let raw = egui::RawInput {
                screen_rect: Some(egui::Rect::from_min_size(
                    egui::Pos2::ZERO,
                    egui::vec2(560.0, 480.0),
                )),
                ..egui::RawInput::default()
            };
            let out = ctx.run(raw, |ctx| {
                let _ = th.apply(ctx);
                egui::CentralPanel::default().show(ctx, |ui| body(ui, &th, &c, list, &mut q, false));
            });
            seen.clear();
            for s in &out.shapes {
                texts(&s.shape, &mut seen);
            }
        }
        seen
    }

