"""Writes crates/ui/src/rtl_table.rs: Arabic contextual forms from the Unicode Character Database
(decompositions <isolated>/<final>/<initial>/<medial> of U+FB50..FDFF and U+FE70..FEFC, via Python's
unicodedata). Rerun after a Python/Unicode upgrade: python tools/gen_arabic_shaping.py"""
import os
import unicodedata as ud

forms = {}  # base -> [iso, fin, ini, med]
lamalef = {}  # alef -> [iso, fin]
IDX = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}
for cp in [*range(0xFB50, 0xFE00), *range(0xFE70, 0xFEFD)]:
    d = ud.decomposition(chr(cp)).split()
    if not d or d[0] not in IDX:
        continue
    base = [int(x, 16) for x in d[1:]]
    if len(base) == 1:
        forms.setdefault(base[0], [0, 0, 0, 0])[IDX[d[0]]] = cp
    elif len(base) == 2 and base[0] == 0x644 and base[1] in (0x622, 0x623, 0x625, 0x627) and d[0] in ("<isolated>", "<final>"):
        lamalef.setdefault(base[1], [0, 0])[IDX[d[0]]] = cp
forms[0x640] = [0x640] * 4  # tatweel joins both sides, keeps its shape
out = ["// Generated by tools/gen_arabic_shaping.py from the Unicode Character Database. Do not edit.",
       "/// (letter, [isolated, final, initial, medial]); 0 = form does not exist. Sorted by letter.",
       "pub(crate) const FORMS: &[(char, [u32; 4])] = &["]
for k in sorted(forms):
    out.append("    ('\\u{%X}', [%s])," % (k, ", ".join("0x%X" % v for v in forms[k])))
out += ["];", "", "/// (alef variant, [isolated, final]) of the mandatory lam+alef ligature.",
        "pub(crate) const LAM_ALEF: &[(char, [u32; 2])] = &["]
for k in sorted(lamalef):
    out.append("    ('\\u{%X}', [0x%X, 0x%X]),"% (k, *lamalef[k]))
out.append("];")
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "ui", "src", "rtl_table.rs")
open(p, "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print(len(forms), "letters,", len(lamalef), "lam-alef")
